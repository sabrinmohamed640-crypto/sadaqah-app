class LocalizationManager extends StatefulWidget {
  final Widget child;
  final AppLanguage initialLanguage;
  const LocalizationManager({
    super.key,
    required this.child,
    this.initialLanguage = AppLanguage.en,
  });

  static LocalizationManagerState of(BuildContext context) {
    final _InheritedLocalization? result =
        context.dependOnInheritedWidgetOfExactType<_InheritedLocalization>();
    assert(result != null, 'No LocalizationManager found in context');
    return result!.data;
  }

  @override
  State<LocalizationManager> createState() => LocalizationManagerState();
}

class LocalizationManagerState extends State<LocalizationManager> {
  late AppLanguage _language;

  @override
  void initState() {
    super.initState();
    _language = widget.initialLanguage;
  }

  AppLanguage get language => _language;
  TextDirection get textDirection =>
      _language == AppLanguage.ar ? TextDirection.rtl : TextDirection.ltr;

  AppLocalization get localization => AppLocalization(_language);

  void toggleLanguage() {
    setState(() {
      _language = _language == AppLanguage.en ? AppLanguage.ar : AppLanguage.en;
    });
  }

  void setLanguage(AppLanguage lang) {
    if (_language != lang) {
      setState(() {
        _language = lang;
      });
    }
  }

  @override
  Widget build(BuildContext context) {
    return _InheritedLocalization(
      data: this,
      child: widget.child,
    );
  }
}

class _InheritedLocalization extends InheritedWidget {
  final LocalizationManagerState data;

  const _InheritedLocalization({
    required this.data,
    required super.child,
  });

  @override
  bool updateShouldNotify(_InheritedLocalization oldWidget) {
    return data.language != oldWidget.data.language;
  }
}

extension LocalizationExtension on BuildContext {
  AppLocalization get loc => LocalizationManager.of(this).localization;
  LocalizationManagerState get locManager => LocalizationManager.of(this);
}

String getGreeting(BuildContext context, {required int hour}) {
  final loc = context.loc;
  if (hour < 12) {
    return loc.translate('greeting_morning');
  } else if (hour < 18) {
    return loc.translate('greeting_afternoon');
  } else {
    return loc.translate('greeting_evening');
  }
}
